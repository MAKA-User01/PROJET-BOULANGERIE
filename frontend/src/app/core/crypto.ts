export function sha256(message: string): string {
  const bytes = Array.from(new TextEncoder().encode(message));
  const bitLength = bytes.length * 8;
  bytes.push(0x80);
  while (bytes.length % 64 !== 56) {
    bytes.push(0);
  }
  for (let shift = 56; shift >= 0; shift -= 8) {
    bytes.push(shift >= 32 ? Math.floor(bitLength / 2 ** shift) & 0xff : (bitLength >>> shift) & 0xff);
  }

  const hash = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
  const w = new Array<number>(64);
  const rotr = (value: number, bits: number) => (value >>> bits) | (value << (32 - bits));

  for (let offset = 0; offset < bytes.length; offset += 64) {
    for (let i = 0; i < 16; i++) {
      const j = offset + i * 4;
      w[i] = (bytes[j] << 24) | (bytes[j + 1] << 16) | (bytes[j + 2] << 8) | bytes[j + 3];
    }
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, h] = hash;
    for (let i = 0; i < 64; i++) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + s1 + ch + K[i] + w[i]) | 0;
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (s0 + maj) | 0;
      h = g; g = f; f = e; e = (d + t1) | 0;
      d = c; c = b; b = a; a = (t1 + t2) | 0;
    }
    hash[0] = (hash[0] + a) | 0; hash[1] = (hash[1] + b) | 0;
    hash[2] = (hash[2] + c) | 0; hash[3] = (hash[3] + d) | 0;
    hash[4] = (hash[4] + e) | 0; hash[5] = (hash[5] + f) | 0;
    hash[6] = (hash[6] + g) | 0; hash[7] = (hash[7] + h) | 0;
  }
  return hash.map((value) => (value >>> 0).toString(16).padStart(8, '0')).join('');
}

export function randomToken(length = 16): string {
  const values = new Uint8Array(length);
  crypto.getRandomValues(values);
  return Array.from(values, (value) => value.toString(16).padStart(2, '0')).join('');
}

/** Hachage itéré et salé : le mot de passe n'est jamais stocké en clair (§9.2). */
export function hashPassword(password: string, salt: string): string {
  let digest = `${salt}:${password}`;
  for (let i = 0; i < 400; i++) {
    digest = sha256(`${salt}${digest}`);
  }
  return digest;
}

export function generateTemporaryPassword(): string {
  const upper = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  const lower = 'abcdefghijkmnopqrstuvwxyz';
  const digits = '23456789';
  const pick = (source: string) => {
    const index = new Uint32Array(1);
    crypto.getRandomValues(index);
    return source[index[0] % source.length];
  };
  return `${pick(upper)}${pick(lower)}${pick(lower)}${pick(lower)}-${pick(digits)}${pick(digits)}${pick(upper)}${pick(lower)}#${pick(digits)}`;
}

export function passwordIssues(password: string): string[] {
  const issues: string[] = [];
  if (password.length < 10) { issues.push('10 caractères minimum'); }
  if (!/[A-Z]/.test(password)) { issues.push('une majuscule'); }
  if (!/[a-z]/.test(password)) { issues.push('une minuscule'); }
  if (!/[0-9]/.test(password)) { issues.push('un chiffre'); }
  if (!/[^A-Za-z0-9]/.test(password)) { issues.push('un caractère spécial'); }
  return issues;
}
